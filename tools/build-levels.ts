/**
 * Bakes campaign levels 21-100 into src/data/generatedLevels.ts.
 * For each level it tries many seeds and keeps the layout whose estimated income is closest to a smooth
 * difficulty curve, then sets the target from that estimate. Re-run only when you want new layouts:
 *   npx vite-node tools/build-levels.ts
 */
import { writeFileSync } from 'node:fs';
import { buildLevelObjects } from '../src/systems/Fields';
import { estimateLevel } from '../src/systems/Balance';
import { OBJECTS } from '../src/config/economy';
import type { LevelDef, LevelObject } from '../src/data/levels';

const short: Record<string, string> = { goldS: 'gS', goldM: 'gM', goldL: 'gL', diamond: 'dm', rockS: 'rS', rockL: 'rL', bag: 'bg', keg: 'kg', chest: 'ch', slime: 'sl' };
const fmt = (o: LevelObject) =>
  o.type === 'beetle' ? `bt(${o.y}, ${o.laneMinX}, ${o.laneMaxX}, ${o.speed}${o.carriesDiamond ? ', true' : ''})` : `${short[o.type]}(${o.x}, ${o.y})`;

const FIRST = 21;
const LAST = 100;
const out: string[] = [];
for (let id = FIRST; id <= LAST; id++) {
  const k = (id - FIRST) / (LAST - FIRST);
  const d = 10 + k * 16;
  const target = Math.round((4850 + (id - FIRST) * 34) / 25) * 25; // smooth, always rising
  const ratio = 0.6 + k * 0.25;
  const wantEst = target / ratio; // closer to the curve = fair difficulty
  const minEst = target / 0.87;
  const swingMult = Math.round((1.25 + k * 0.1) * 100) / 100;
  let best: { seed: number; objs: LevelObject[]; est: number; err: number } | null = null;
  for (let s = 0; s < 600; s++) {
    const seed = id * 1000 + s;
    const objs = buildLevelObjects(seed, d);
    if (objs.filter((o) => OBJECTS[o.type].collectible).length < 18) continue;
    const probe: LevelDef = { id, name: 'x', target: 1, objects: objs, swingMult };
    const est = estimateLevel(probe).estimate;
    const err = Math.abs(est - wantEst) / wantEst + (est < minEst ? 1 : 0);
    if (!best || err < best.err) best = { seed, objs, est, err };
    if (err < 0.03) break;
  }
  if (!best) throw new Error('no layout for ' + id);
  if (target / best.est > 0.88) console.error('WARNING high ratio at', id);
  const sorted = [...best.objs].sort((a, b) => a.y - b.y);
  const lines: string[] = [];
  for (let i = 0; i < sorted.length; i += 5) lines.push('      ' + sorted.slice(i, i + 5).map(fmt).join(', ') + ',');
  out.push(`  { id: ${id}, name: 'L${id}', target: ${target}, swingMult: ${swingMult}, objects: [\n${lines.join('\n')}\n    ] },`);
  console.error(`L${id} est=${best.est} want=${Math.round(wantEst)} target=${target} objs=${best.objs.length} ratio=${(target / best.est).toFixed(2)}`);
}
const header = `// GENERATED by tools/build-levels.ts - baked campaign levels 21-100 (edit freely, they are plain data).
import type { LevelDef, LevelObject } from './levels';

const t = (type: LevelObject['type'], x: number, y: number): LevelObject => ({ type, x, y });
const gS = (x: number, y: number) => t('goldS', x, y);
const gM = (x: number, y: number) => t('goldM', x, y);
const gL = (x: number, y: number) => t('goldL', x, y);
const dm = (x: number, y: number) => t('diamond', x, y);
const rS = (x: number, y: number) => t('rockS', x, y);
const rL = (x: number, y: number) => t('rockL', x, y);
const bg = (x: number, y: number) => t('bag', x, y);
const kg = (x: number, y: number) => t('keg', x, y);
const ch = (x: number, y: number) => t('chest', x, y);
const sl = (x: number, y: number) => t('slime', x, y);
const bt = (y: number, laneMinX: number, laneMaxX: number, speed: number, carriesDiamond = false): LevelObject => ({
  type: 'beetle',
  x: Math.round(laneMinX + (laneMaxX - laneMinX) * 0.35),
  y,
  laneMinX,
  laneMaxX,
  speed,
  carriesDiamond,
});

export const GENERATED_LEVELS: LevelDef[] = [
`;
writeFileSync('src/data/generatedLevels.ts', header + out.join('\n') + '\n];\n');
